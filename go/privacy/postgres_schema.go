package privacy

import (
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const CurrentSchemaVersion uint = 1

//go:embed schema/*.sql
var privacySchemaFiles embed.FS

type Migration struct {
	Version uint
	Digest  string
	UpSQL   string
	DownSQL string
}

type WrittenMigration struct {
	UpPath   string
	DownPath string
	Digest   string
}

func Schema(version uint) (Migration, error) {
	if version != CurrentSchemaVersion {
		return Migration{}, fmt.Errorf("privacy: unsupported schema version %d", version)
	}
	up, err := privacySchemaFiles.ReadFile("schema/v1.up.sql")
	if err != nil {
		return Migration{}, fmt.Errorf("privacy: read up schema: %w", err)
	}
	down, err := privacySchemaFiles.ReadFile("schema/v1.down.sql")
	if err != nil {
		return Migration{}, fmt.Errorf("privacy: read down schema: %w", err)
	}
	sum := sha256.Sum256(append(append([]byte(nil), up...), down...))
	return Migration{Version: version, Digest: hex.EncodeToString(sum[:]), UpSQL: string(up), DownSQL: string(down)}, nil
}

func WriteMigration(directory, name string, version uint) (WrittenMigration, error) {
	if strings.TrimSpace(directory) == "" {
		return WrittenMigration{}, errors.New("privacy: migration directory is required")
	}
	if strings.TrimSpace(name) == "" || filepath.Base(name) != name {
		return WrittenMigration{}, errors.New("privacy: migration name must be a base filename")
	}
	migration, err := Schema(version)
	if err != nil {
		return WrittenMigration{}, err
	}
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return WrittenMigration{}, fmt.Errorf("privacy: create migration directory: %w", err)
	}
	header := fmt.Sprintf(
		"-- Code generated by foundation privacy; DO NOT EDIT.\n-- privacy-schema-version: %d\n-- privacy-schema-digest: %s\n\n",
		migration.Version, migration.Digest,
	)
	result := WrittenMigration{
		UpPath:   filepath.Join(directory, name+".up.sql"),
		DownPath: filepath.Join(directory, name+".down.sql"), Digest: migration.Digest,
	}
	if err := writePrivacyMigration(result.UpPath, []byte(header+migration.UpSQL)); err != nil {
		return WrittenMigration{}, err
	}
	if err := writePrivacyMigration(result.DownPath, []byte(header+migration.DownSQL)); err != nil {
		return WrittenMigration{}, err
	}
	return result, nil
}

func writePrivacyMigration(path string, content []byte) error {
	existing, err := os.ReadFile(path)
	if err == nil {
		if string(existing) == string(content) {
			return nil
		}
		return fmt.Errorf("privacy: migration drift at %s", path)
	}
	if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("privacy: read migration %s: %w", path, err)
	}
	if err := os.WriteFile(path, content, 0o644); err != nil {
		return fmt.Errorf("privacy: write migration %s: %w", path, err)
	}
	return nil
}
